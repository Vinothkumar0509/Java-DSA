package character;

public class ASCIIDemo {

    public static void main(String[] args) {
        char c = '9';
        int asciiValue = c;

        System.out.println(asciiValue);

        // ASCII value to character

        int ascIIValue = 72;
        char character = (char) ascIIValue;

        System.out.println(character);
    }
}